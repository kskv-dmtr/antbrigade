/* Приведение строки к виду, по которому идёт поиск.

   Задача одна: чтобы «Curió Curió» находилось по `curio`, «Lindstrøm» по
   `lindstrom`, а «O’Flynn» по `o'flynn` с обычным апострофом. В каталоге
   106 знаков вне латиницы с цифрами, и набрать их на своей клавиатуре
   может далеко не всякий — а искать по ним приходится.

   Через эту же функцию проходит и то, что набрали в поле: обе стороны
   сравнения приводятся одинаково, поэтому написание с диакритикой тоже
   продолжает работать — `curió` складывается в тот же `curio`.

   Порядок действий важен: сначала регистр, потом разложение, и только
   потом подстановка. Ъ-образные буквы вроде `ø` разложение не берёт, а
   `Ó` — берёт, и если подставлять раньше, до подстановки дойдёт уже
   разобранная строка. */

/* Буквы, у которых нет разложения в NFD: диакритика в них вросла в сам
   знак. Их приходится перечислять руками — Unicode тут не помощник.

   Список собран по каталогу и дополнен соседями по алфавитам, чтобы новая
   запись из Notion не потребовала правки кода: скандинавские ø и æ,
   польские ł, исландские þ и ð, немецкая ß, турецкая ı, лигатуры œ.

   `µ` → `u`, а не `mu`: артист пишется `µ-Ziq`, и по-русски его набирают
   как `u-ziq`. Общая часть `ziq` находится при любом выборе, а из двух
   написаний целиком мы можем поддержать только одно.

   `Σ` → `s` ради `Σtella`: имя читается «Стелла», и первая буква здесь —
   именно латинская S, нарисованная греческой. */
const БУКВЫ = {
  ø: 'o', æ: 'ae', œ: 'oe', ł: 'l', đ: 'd', ð: 'd', þ: 'th',
  ß: 'ss', ħ: 'h', ı: 'i', ŋ: 'n', ĸ: 'k', ʒ: 'z', ə: 'e',
  µ: 'u', σ: 's', ς: 's'
};

/* Типографика: в названиях стоят настоящие кавычки и тире, а на
   клавиатуре — прямые. `’` встречается в каталоге семьдесят раз, прямой
   апостроф — двадцать два: без подстановки половина названий не находится
   тем знаком, который набирают.

   Апостроф вдобавок исчезает совсем — и в названии, и в запросе: набирая
   «O’Flynn», его чаще пропускают, чем ставят, а обе стороны сравнения
   проходят через эту функцию, и написание со знаком продолжает работать.
   Прочую пунктуацию не трогаем: выброси её всю — и «!!!» останется с пустым
   ключом и перестанет находиться по собственному имени. */
const ЗНАКИ = {
  '’': '', '‘': '', '‚': '', '‛': '', "'": '', '`': '', '´': '',
  '“': '"', '”': '"', '„': '"', '«': '"', '»': '"',
  '–': '-', '—': '-', '−': '-', '‑': '-', '‒': '-',
  '…': '...', ' ': ' ', ' ': ' ', ' ': ' '
};

const ПОДСТАНОВКА = { ...БУКВЫ, ...ЗНАКИ };

/* Один проход по строке вместо десятка replace: подстановок под сорок, а
   строк — три тысячи на сборке и одна на каждое нажатие клавиши. */
export function fold(text) {
  const исходник = String(text ?? '')
    .toLowerCase()
    .normalize('NFD')
    // Диакритика после разложения — отдельными знаками; убираем их.
    .replace(/[̀-ͯ]/g, '');

  let итог = '';
  for (const знак of исходник) итог += ПОДСТАНОВКА[знак] ?? знак;
  return итог;
}

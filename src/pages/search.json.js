/* Сводный указатель для поиска в шапке.

   Отдаётся одним файлом /search.json и грузится в браузер по первому касанию
   поля, а не вместе со страницей: искать заходят не все, а весит он больше
   любой страницы сайта.

   Строка записи — массив, а не объект: имена ключей повторились бы на каждой
   из трёх с половиной тысяч записей и заняли бы больше самих значений.
   Отдаётся объектом: { картинки, записи }. Порядок полей записи: тип, имя,
   адрес, подпись, пометка справа, миниатюра, род.

   Род — то, что стоит в рамке справа от находки: у релиза его тип («Album»,
   «EP»), у ролика — вид («Official Video»); с 20 сентября 2026, просьба
   владельца, до того стояли общие «release» и «video». У исполнителя, лейбла
   и жанра — слово рода (Artist, Label, Genre). Род лежит у всех записей и всегда седьмым: скрипт
   поля дописывает к записи свои поля (свёрнутые имя и подпись), и место рода
   должно быть постоянным.

   Страны у исполнителя и лейбла в подписи нет — с 19 сентября 2026 (просьба
   владельца): подпись у них — один счёт релизов.

   Миниатюра — с 19 сентября 2026 (находки набраны по образцу Spotify):
   «c» и id обложки либо «v» и id ролика, полный адрес собирает скрипт
   У релиза и клипа это номер его картинки в общем списке, у исполнителя,
   лейбла и жанра — набор номеров: обложки их релизов, из которых браузер
   выбирает при каждой загрузке. Нет скачанной картинки — пусто.

   Тип одной буквой: r — релиз, v — клип, a — исполнитель, l — лейбл,
   g — жанр. Развернёт его в слово тот же скрипт, что рисует находки.

   Свёрнутой формы имени (без регистра и без диакритики) здесь нет намеренно:
   она удвоила бы вес файла, а в браузере считается за один проход по всему
   указателю. */

import {
  albums, artists, labels, genres, videos,
  artistLine, videoTitle, videoArtists, typeLine,
  albumById, videoById, coverSrc, thumbSrc
} from '../lib/db.js';

/* Картинки лежат отдельным списком, а в записи стоят их номера: адрес
   обложки — 36 знаков, и при одной картинке на запись они занимали треть
   файла. Теперь список общий (одна обложка служит и релизу, и его
   исполнителю, и лейблу, и жанру), а номер — три-четыре знака.

   У исполнителя, лейбла и жанра номеров несколько: браузер выбирает из них
   при каждой загрузке страницы — как «Random Picks» на витрине тасует
   каталог (20 сентября 2026, просьба владельца). Жребий при сборке этого не
   давал: без нового коммита сайт не пересобирается, и обложка застывала.

   Больше ШЕСТИ не берём: с шестью разворот уже не приедается, а лишние
   номера — лишний вес на 2244 записи. Выбираются они наугад при сборке,
   поэтому у жанра с сотней релизов раз от раза попадаются разные. */
const КАРТИНОК = 6;

const картинки = [];
const номера = new Map();

const номер = (адрес) => {
  if (!адрес) return null;
  if (!номера.has(адрес)) {
    номера.set(адрес, картинки.length);
    картинки.push(адрес);
  }
  return номера.get(адрес);
};

/* Адрес картинки — коротким видом: «c» и id обложки либо «v» и id ролика.
   Полный адрес собирает скрипт поля. */
const обложка = (al) => {
  const src = coverSrc(al, 400);
  const m = src && src.match(/^\/covers\/(.+)-400\.webp$/);
  return m ? 'c' + m[1] : '';
};
const кадр = (v) => {
  const src = thumbSrc(v, 480);
  const m = src && src.match(/^\/videos\/(.+)-480\.webp$/);
  return m ? 'v' + m[1] : '';
};

/* Перетасовать и взять не больше КАРТИНОК штук. */
const горсть = (список) => {
  const с = [...список];
  for (let i = с.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [с[i], с[j]] = [с[j], с[i]];
  }
  return с.slice(0, КАРТИНОК);
};

/* Номера картинок записи: обложки её релизов, а у исполнителя без релизов —
   кадры его клипов. */
const миниатюры = (albumIds = [], videoIds = []) => {
  const свои = albumIds
    .map((id) => albumById.get(id))
    .filter(Boolean)
    .map(обложка)
    .filter(Boolean);

  if (!свои.length) {
    for (const id of videoIds) {
      const k = кадр(videoById.get(id));
      if (k) свои.push(k);
    }
  }

  return горсть(свои).map(номер);
};

export function GET() {
  const записи = [];

  /* Исполнители первыми: при равном совпадении имя человека или группы —
     чаще то, что искали, чем одноимённый релиз. */
  for (const a of artists) {
    записи.push(['a', a.name, `/artists/${a.slug}`,
      '', typeLine(a.albumIds, a.videoIds),
      миниатюры(a.albumIds, a.videoIds), 'Artist']);
  }

  for (const al of albums) {
    записи.push(['r', al.album, `/music/${al.slug}`, artistLine(al), String(al.year ?? ''), номер(обложка(al)),
      al.types?.[0] ?? 'release']);
  }

  for (const v of videos) {
    записи.push(['v', videoTitle(v), `/video/${v.slug}`, videoArtists(v), String(v.year ?? ''), номер(кадр(v)),
      v.kind ?? 'video']);
  }

  for (const l of labels) {
    записи.push(['l', l.name, `/labels/${l.slug}`,
      '', typeLine(l.albumIds),
      миниатюры(l.albumIds), 'Label']);
  }

  for (const g of genres) {
    записи.push(['g', g.name, `/genres/${g.slug}`, '', typeLine(g.albumIds), миниатюры(g.albumIds), 'Genre']);
  }

  return new Response(JSON.stringify({ картинки, записи }), {
    headers: { 'content-type': 'application/json; charset=utf-8' }
  });
}
